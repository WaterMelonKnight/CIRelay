import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import process from 'node:process';

const packageDirectory = resolve(import.meta.dirname, '../packages/mcp');
const sourceDirectory = join(packageDirectory, 'src');
const generatedFile = join(sourceDirectory, 'build-metadata.ts');

function sourceHash() {
  const hash = createHash('sha256');
  for (const file of readdirSync(sourceDirectory, { recursive: true })
    .filter((entry) => typeof entry === 'string')
    .filter((entry) => entry.endsWith('.ts') && entry !== 'build-metadata.ts')
    .sort()) {
    hash.update(relative(sourceDirectory, join(sourceDirectory, file)));
    hash.update('\0');
    hash.update(readFileSync(join(sourceDirectory, file)));
    hash.update('\0');
  }
  return hash.digest('hex');
}

if (!process.argv.includes('--no-clean')) {
  rmSync(join(packageDirectory, 'dist'), { recursive: true, force: true });
}

const { version } = JSON.parse(
  readFileSync(join(packageDirectory, 'package.json'), 'utf8'),
);
writeFileSync(
  generatedFile,
  `// Generated by scripts/prepare-mcp-build.mjs; do not edit.\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(version)};\n` +
    `export const SOURCE_HASH = ${JSON.stringify(sourceHash())};\n`,
);
